#!/usr/bin/env python3
"""The battle cameras' table (BtlCameraTable::Initialize, btl_camera_name_table) as C++:
engine/src/battle/cameratable.inc.

BtlCameraTable is built in code: s16 camera numbers from +4 - GetStart(k) +4 + 2k,
GetAttackFromEnemy(m, t) +0x7c + 2 (4m + t), GetAttackToEnemy(a, p) +0x12c + 2 (22a + p),
GetPatternToCamera(p) +0x1dc + 2p, ... - each an index into btl_camera_name_table, the cameras'
names (the joints of BattleCamera_move / _nomove: BtlCameraCtrl::Start). This reads the
Initialize function's stores from the decompilation and the names from the library (its pointer
table in the data segment, as stored - unrelocated - in the file).

  gen_camera_table.py <decomp.c> <libChaosRings2.so (armv7)> > engine/src/battle/cameratable.inc
"""
import re
import struct
import sys

BASE = 0x10000  # (Ghidra's image base for the armv7 library)


def file_offset(lib, vaddr):
    """a virtual address (the library's, base 0) as a file offset, by its program headers"""
    phoff, = struct.unpack_from('<I', lib, 0x1c)
    phnum, = struct.unpack_from('<H', lib, 0x2c)
    for i in range(phnum):
        p_type, p_offset, p_vaddr, _, p_filesz = struct.unpack_from('<5I', lib, phoff + i * 32)
        if p_type == 1 and p_vaddr <= vaddr < p_vaddr + p_filesz:
            return vaddr - p_vaddr + p_offset
    return None


def main(argv):
    if len(argv) < 3:
        print(__doc__)
        return 1
    src = open(argv[1], encoding='utf-8', errors='replace').read()
    lib = open(argv[2], 'rb').read()
    start = src.index('/* BtlCameraTable::Initialize(BtlMain*) */')
    end = src.index('\n// ---- ', start)
    shorts = {}
    store = re.compile(r'\*\(undefined2 \*\)\(param_1 \+ (0x[0-9a-f]+|\d+)\) = (0x[0-9a-f]+|\d+);')
    for line in src[start:end].splitlines():
        m = store.match(line.strip())
        if m:
            shorts[int(m.group(1), 0)] = struct.unpack('<h', struct.pack('<H', int(m.group(2), 0) & 0xffff))[0]
    sym = re.search(r'([0-9a-f]+) D btl_camera_name_table', open(argv[1].replace('decomp.c', 'symbols.txt')).read())
    table = int(sym.group(1), 16)  # (symbols.txt: the library's own addresses, base 0)
    names = []
    o = file_offset(lib, table)
    count = max(shorts.values()) + 1 if shorts else 0  # (as far as the table's numbers reach)
    for k in range(count):
        ptr, = struct.unpack_from('<I', lib, o + 4 * k)
        so = file_offset(lib, ptr)
        s = lib[so:so + 64].split(b'\0')[0].decode('latin-1') if so is not None and ptr else ''
        names.append(s if s.startswith('Cam_') else '')  # (the others: a placeholder)
    top = max(shorts) + 2 if shorts else 4
    vals = [shorts.get(off, -1) for off in range(4, top, 2)]
    out = ['// Generated by tools/gen_camera_table.py from BtlCameraTable::Initialize and',
           '// btl_camera_name_table - do not edit. kCameraShorts[k]: the table\'s s16 at +4 + 2k (-1 unset);',
           '// kCameraNames: the cameras by number.',
           'static const short kCameraShorts[%d] = {' % len(vals)]
    for i in range(0, len(vals), 16):
        out.append('    ' + ', '.join(str(v) for v in vals[i:i + 16]) + ',')
    out.append('};')
    out.append('static const char* const kCameraNames[%d] = {' % len(names))
    for n in names:
        out.append('    "%s",' % n if n else '    nullptr,')
    out.append('};')
    print('\n'.join(out))
    print('// %d table entries, %d names' % (len(shorts), len(names)), file=sys.stderr)
    return 0


if __name__ == '__main__':
    sys.exit(main(sys.argv))
