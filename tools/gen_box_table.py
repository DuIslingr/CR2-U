#!/usr/bin/env python3
"""The treasure boxes' contents (Cr3TreasureBox::GetItemID) as C++: engine/src/field/boxtable.inc.

Each visit to a dungeon draws a table (Cr3TreasureBox::choiceTable: the difficulty,
cr3_common_data[0], x 3 + one of 3 at random); a table's row in the library holds ten items -
the seven normal boxes' (tbox) in the order of those placed, the two key boxes' (obox), the
first fixed box's (fbox) - and a second table seven, one by character (the fixed boxes 1 and 2:
the party's two). -1: none. Their addresses are read from the decompilation's GetItemID, the
values from the library; the tables run up to the voice table's (Cr3VoiceTable) start.

  gen_box_table.py <decomp.c> <libChaosRings2.so (armv7)> > engine/src/field/boxtable.inc
"""
import re
import struct
import sys

BASE = 0x10000


def file_offset(lib, vaddr):
    phoff, = struct.unpack_from('<I', lib, 0x1c)
    phnum, = struct.unpack_from('<H', lib, 0x2c)
    for i in range(phnum):
        p_type, p_offset, p_vaddr, _, p_filesz = struct.unpack_from('<5I', lib, phoff + i * 32)
        if p_type == 1 and p_vaddr <= vaddr < p_vaddr + p_filesz:
            return vaddr - p_vaddr + p_offset
    return None


def body(src, signature):
    start = src.index('/* %s */' % signature)
    return src[start:src.index('\n// ---- ', start)]


def main(argv):
    if len(argv) < 3:
        print(__doc__)
        return 1
    src = open(argv[1], encoding='utf-8', errors='replace').read()
    lib = open(argv[2], 'rb').read()
    g = body(src, 'Cr3TreasureBox::GetItemID(int, int)')
    items = int(re.search(r'&DAT_([0-9a-f]+) \+ \(iVar1 \+ \*\(int \*\)this \* 10\) \* 4', g).group(1), 16) - BASE
    charas = int(re.search(r'&DAT_([0-9a-f]+) \+ \(\*\(int \*\)this \* 7', g).group(1), 16) - BASE
    voices = int(re.search(r'&DAT_([0-9a-f]+) \+ \(iVar2 \* 1000', body(src, 'Cr3VoiceTable(char const*, int)')).group(1), 16) - BASE
    tables = (charas - items) // 40
    assert tables == (voices - charas) // 28, (tables, voices - charas)
    it = struct.unpack_from('<%di' % (tables * 10), lib, file_offset(lib, items))
    ch = struct.unpack_from('<%di' % (tables * 7), lib, file_offset(lib, charas))
    out = ['// Generated by tools/gen_box_table.py from Cr3TreasureBox\'s tables - do not edit.',
           '// kBoxItems[table]: 7 normal boxes\', 2 key boxes\', the first fixed box\'s; kBoxCharaItems[table]:',
           '// the fixed boxes 1 / 2\'s by character (from 0). -1 none.',
           'static const short kBoxItems[%d][10] = {' % tables]
    for t in range(tables):
        out.append('    {' + ', '.join(str(x) for x in it[t * 10:t * 10 + 10]) + '},')
    out.append('};')
    out.append('static const short kBoxCharaItems[%d][7] = {' % tables)
    for t in range(tables):
        out.append('    {' + ', '.join(str(x) for x in ch[t * 7:t * 7 + 7]) + '},')
    out.append('};')
    print('\n'.join(out))
    return 0


if __name__ == '__main__':
    sys.exit(main(sys.argv))
