#!/usr/bin/env python3
"""The monsters' death effects' heights (BtlEffectTable::GetEffectDeadOffsetByModelName) as C++:
engine/src/battle/deadtable.inc.

A table in the library's .data (0x5c061c in Ghidra's addresses, 71 entries of 12 bytes): +0x00 the
hash of +0x04's name (made at the first lookup), +0x04 a figure's name (its first four
characters), +0x08 a float - how far above its place eff201 / eff202 go as it dies
(BtlActionCtrl::ActionDeadStart / ActionDeadWaitBossMotion). Those without a height are left out.

  gen_dead_table.py <libChaosRings2.so (armv7)> > engine/src/battle/deadtable.inc
"""
import struct
import sys

BASE = 0x10000
TABLE, ENTRY, COUNT = 0x5c061c, 12, 71


def file_offset(lib, vaddr):
    phoff, = struct.unpack_from('<I', lib, 0x1c)
    phnum, = struct.unpack_from('<H', lib, 0x2c)
    for i in range(phnum):
        p_type, p_offset, p_vaddr, _, p_filesz = struct.unpack_from('<5I', lib, phoff + i * 32)
        if p_type == 1 and p_vaddr <= vaddr < p_vaddr + p_filesz:
            return vaddr - p_vaddr + p_offset
    return None


def main(argv):
    if len(argv) < 2:
        print(__doc__)
        return 1
    lib = open(argv[1], 'rb').read()
    o = file_offset(lib, TABLE - BASE)
    rows = []
    for k in range(COUNT):
        _, name_at, height = struct.unpack_from('<IIf', lib, o + k * ENTRY)
        s = file_offset(lib, name_at)
        name = lib[s:s + 8].split(b'\0')[0].decode('latin-1')
        if height != 0:
            t = '%.7g' % height
            rows.append('    {"%s", %s},' % (name, t + ('f' if '.' in t or 'e' in t else '.0f')))
    out = ['// Generated by tools/gen_dead_table.py from BtlEffectTable\'s death offsets - do not edit.',
           '// {a figure (its first four characters), how far above it its death effect goes}.',
           'static const struct { const char* name; float height; } kDeadOffsets[%d] = {' % len(rows)]
    out += rows
    out.append('};')
    print('\n'.join(out))
    return 0


if __name__ == '__main__':
    sys.exit(main(sys.argv))
