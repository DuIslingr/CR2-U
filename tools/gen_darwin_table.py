#!/usr/bin/env python3
"""Darwin's third awakening's offsets (BtlActionTable) as C++: engine/src/battle/darwintable.inc.

Two tables built by a static initializer (_INIT_4, writing .bss; Ghidra's addresses), entries of
0x30 bytes, each +0x10..+0x18 a Vector3 in hundredths:
  0x5d53a0, 71: GetAwakeDawinLv3Offset - by the one struck's figure (+0x04 its name, the first four
        characters; +0x00 their hash, made at the first lookup): where Darwin stands from it
        (ActionSpecialAwakeDawin3DawinOffset) and the camera from where it was (CameraOffset)
  0x5d60f0, 17: GetAwakeDawinLv3CameraOffset - by +0x00, the monsters' size pattern (BtlWork +0x51;
        13 / 14 for one of the party struck, solo / paired): the camera's place, Darwin's from the
        one struck (CameraOffset2)
This reads the initializer's decompilation (re/android/armv7/decomp.c), its stores, and the names
from the library.

  gen_darwin_table.py <decomp.c> <libChaosRings2.so (armv7)> > engine/src/battle/darwintable.inc
"""
import re
import struct
import sys

BASE = 0x10000
FIGURES, NFIGURES = 0x5d53a0, 71
PATTERNS, NPATTERNS = 0x5d60f0, 17
ENTRY = 0x30


def file_offset(lib, vaddr):
    phoff, = struct.unpack_from('<I', lib, 0x1c)
    phnum, = struct.unpack_from('<H', lib, 0x2c)
    for i in range(phnum):
        p_type, p_offset, p_vaddr, _, p_filesz = struct.unpack_from('<5I', lib, phoff + i * 32)
        if p_type == 1 and p_vaddr <= vaddr < p_vaddr + p_filesz:
            return vaddr - p_vaddr + p_offset
    return None


def main(argv):
    if len(argv) < 3:
        print(__doc__)
        return 1
    src = open(argv[1], encoding='utf-8', errors='replace').read()
    lib = open(argv[2], 'rb').read()
    body = None
    for m in re.finditer(r'\nvoid (_INIT_\d+)\(void\)\s*\{\n(.*?)\n\}\n', src, re.S):
        if re.search(r'\bDAT_%08x = ' % (FIGURES + 4), m.group(2)):
            body = m.group(2)
            break
    if body is None:
        raise SystemExit('no initializer writes the table')
    mem = {}
    for m in re.finditer(r'^\s*_?DAT_([0-9a-f]{8}) = (.*?);$', body, re.M):
        mem[int(m.group(1), 16)] = m.group(2)

    def string(v):
        m = re.fullmatch(r'&DAT_([0-9a-f]+)', v or '')
        if not m:
            return None
        o = file_offset(lib, int(m.group(1), 16) - BASE)
        return lib[o:o + 16].split(b'\0')[0].decode('latin-1')

    def num(v):
        try:
            return int(v, 0)
        except (TypeError, ValueError):
            return 0

    def flt(v):
        return struct.unpack('<f', struct.pack('<I', num(v) & 0xffffffff))[0]

    def fl(x):
        t = '%.7g' % x
        return t + ('f' if ('.' in t or 'e' in t) else '.0f')

    def offset(a):
        return ', '.join(fl(flt(mem.get(a + 0x10 + 4 * c))) for c in range(3))

    out = ['// Generated by tools/gen_darwin_table.py from BtlActionTable\'s static initializer - do not',
           '// edit. Darwin\'s third awakening: by the one struck\'s figure, by the size pattern; in',
           '// hundredths (battle/special.hpp).',
           'static const DarwinOffset kDarwinFigureOffsets[%d] = {' % NFIGURES]
    for k in range(NFIGURES):
        a = FIGURES + k * ENTRY
        name = string(mem.get(a + 4))
        out.append('    {%s, {%s}},' % ('"%s"' % name if name else 'nullptr', offset(a)))
    out.append('};')
    out.append('static const DarwinPatternOffset kDarwinPatternOffsets[%d] = {' % NPATTERNS)
    for k in range(NPATTERNS):
        a = PATTERNS + k * ENTRY
        out.append('    {%d, {%s}},' % (num(mem.get(a)), offset(a)))
    out.append('};')
    print('\n'.join(out))
    return 0


if __name__ == '__main__':
    sys.exit(main(sys.argv))
