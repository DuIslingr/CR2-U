#!/usr/bin/env python3
"""The interface's digits (DotNumParamPackTable: DotNumId2's glyphs in hud_dotnum) as C++:
engine/src/gfx/dotnumtable.inc.

0x18 bytes a glyph, by its number (a digit set's first + the digit): f32 width, height (pixels of
a 1000-a-unit layout), u0, v0, u1, v1 - read from the library's data segment (the table as the
file stores it), as far as its entries are glyphs.

  gen_dotnum_table.py <decomp.c> <libChaosRings2.so (armv7)> > engine/src/gfx/dotnumtable.inc
"""
import re
import struct
import sys


def file_offset(lib, vaddr):
    phoff, = struct.unpack_from('<I', lib, 0x1c)
    phnum, = struct.unpack_from('<H', lib, 0x2c)
    for i in range(phnum):
        p_type, p_offset, p_vaddr, _, p_filesz = struct.unpack_from('<5I', lib, phoff + i * 32)
        if p_type == 1 and p_vaddr <= vaddr < p_vaddr + p_filesz:
            return vaddr - p_vaddr + p_offset
    return None


def main(argv):
    if len(argv) < 3:
        print(__doc__)
        return 1
    sym = re.search(r'([0-9a-f]+) D DotNumParamPackTable', open(argv[1].replace('decomp.c', 'symbols.txt')).read())
    lib = open(argv[2], 'rb').read()
    o = file_offset(lib, int(sym.group(1), 16))  # (symbols.txt: the library's own addresses)
    rows = []
    while True:
        f = struct.unpack_from('<6f', lib, o + 24 * len(rows))
        ok = all(x == int(x) and 0 <= x <= 512 for x in f[:2]) and all(0 <= x <= 1 for x in f[2:])
        if not ok:
            break
        rows.append(f)
    while rows and not rows[-1][0]:
        rows.pop()
    out = ['// Generated by tools/gen_dotnum_table.py from DotNumParamPackTable - do not edit.',
           '// A glyph by its number: width, height (1000-a-unit pixels), u0, v0, u1, v1 of hud_dotnum.',
           'static const float kDotNum[%d][6] = {' % len(rows)]
    for f in rows:
        out.append('    {' + ', '.join('%.9gf' % x if x != int(x) else '%d' % int(x) for x in f) + '},')
    out.append('};')
    print('\n'.join(out))
    print('// %d glyphs' % len(rows), file=sys.stderr)
    return 0


if __name__ == '__main__':
    sys.exit(main(sys.argv))
