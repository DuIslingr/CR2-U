#!/usr/bin/env python3
"""engine/src/script/native_api.inc from tools/sq_bindings.py's listing: the scripts' native tables
and their functions' names (the engine binds each; unimplemented ones are stubs).

  sq_bindings.py <decomp.c> <lib> > re/sq_bindings.txt
  gen_native_api.py re/sq_bindings.txt engine/src/script/native_api.inc
"""
import sys

tables, order = {}, []
cur = None
for line in open(sys.argv[1]):
    if not line.startswith('    '):
        cur = line.split()[0]
        if cur not in tables:
            tables[cur] = []
            order.append(cur)
    else:
        name = line.split()[0]
        if name not in tables[cur]:
            tables[cur].append(name)
out = ['// Generated by tools/gen_native_api.py from the Android library\'s Cr3Bind* functions',
       '// (tools/sq_bindings.py): table -> the functions Cr3BindNativeClosure gives it']
for t in order:
    if t.startswith('_'):  # (Cr3BindVectorStruct's accessors)
        continue
    names = ', '.join(f'"{n}"' for n in tables[t])
    out.append(f'{{"{t}", {{{names}}}}},')
open(sys.argv[2], 'w').write('\n'.join(out) + '\n')
print(f'{sum(len(tables[t]) for t in order if not t.startswith("_"))} functions in '
      f'{len([t for t in order if not t.startswith("_")])} tables')
