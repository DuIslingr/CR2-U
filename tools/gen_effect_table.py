#!/usr/bin/env python3
"""The battle effects' settings (BtlEffectTable) as C++: engine/src/battle/effecttable.inc.

BtlEffectTable is built by a static initializer (_INIT_5, writing .bss: 166 entries of 0x50 bytes
from 0x5d6440 in Ghidra's addresses), looked up by name (GetEffectSetting: else "common"). What
BtlEffectCtrl::CreateEffect and BtlEffect::Pose read of an entry:
  +0x04 the name   +0x10 the shift (Vector3: added to where it follows)   +0x20 the scale
  +0x30 s16 the locator it follows (BtlTposTable's: 0 RootLocator .. 6 DummyDP02, 7 DummyCPS,
        8 DummyCP, 9 the model's place; a command's effect: 7 the side's middle, once - HitGroupEffect)
  +0x32 s16 the same for a pair's action (SetCommandEffectPosition: 7 the side's middle)
  +0x34 s16 0 placed by its target, else left where it was made
  +0x36 turned to the camera   +0x37 looping   +0x3a scaled to its target (BtlEffect::SetScale)
  +0x3c a shot's path (BtlEffectCtrl::ControlShot: 0 straight, 1 falling)
  +0x39 what it follows (SetTargetConstrain: 1 the position, 2 the rotation, 4 the joint's scale)
  +0x3b its kind   +0x3e u16 a delay (frames: its start that much later, hidden till then)
This reads the initializer's decompilation (re/android/armv7/decomp.c), its stores in order, and
the names from the library.

  gen_effect_table.py <decomp.c> <libChaosRings2.so (armv7)> > engine/src/battle/effecttable.inc
"""
import re
import struct
import sys

BASE = 0x10000
TABLE, ENTRY, COUNT = 0x5d6440, 0x50, 0xa6


def file_offset(lib, vaddr):
    phoff, = struct.unpack_from('<I', lib, 0x1c)
    phnum, = struct.unpack_from('<H', lib, 0x2c)
    for i in range(phnum):
        p_type, p_offset, p_vaddr, _, p_filesz = struct.unpack_from('<5I', lib, phoff + i * 32)
        if p_type == 1 and p_vaddr <= vaddr < p_vaddr + p_filesz:
            return vaddr - p_vaddr + p_offset
    return None


def main(argv):
    if len(argv) < 3:
        print(__doc__)
        return 1
    src = open(argv[1], encoding='utf-8', errors='replace').read()
    lib = open(argv[2], 'rb').read()
    # the initializer: the _INIT_ function that writes the table's first entry's name
    body = None
    for m in re.finditer(r'\nvoid (_INIT_\d+)\(void\)\s*\{\n(.*?)\n\}\n', src, re.S):
        if re.search(r'\bDAT_%08x = ' % (TABLE + 4), m.group(2)):
            body = m.group(2)
            break
    if body is None:
        raise SystemExit('no initializer writes the table')
    mem = {}
    for m in re.finditer(r'^\s*_?DAT_([0-9a-f]{8}) = (.*?);$', body, re.M):
        mem[int(m.group(1), 16)] = m.group(2)

    def string(v):
        if v is None:
            return None
        m = re.fullmatch(r'"(.*)"', v)
        if m:
            return m.group(1)
        m = re.fullmatch(r'&DAT_([0-9a-f]+)', v)
        if m:
            o = file_offset(lib, int(m.group(1), 16) - BASE)
            return lib[o:o + 64].split(b'\0')[0].decode('latin-1')
        return None

    def num(v, default=0):
        if v is None:
            return default
        try:
            return int(v, 0)
        except ValueError:
            return default

    def flt(v):
        b = num(v, 0) & 0xffffffff
        return struct.unpack('<f', struct.pack('<I', b))[0]

    def fl(x):
        t = '%.7g' % x
        return t + ('f' if ('.' in t or 'e' in t) else '.0f')

    out = ['// Generated by tools/gen_effect_table.py from BtlEffectTable\'s static initializer - do not',
           '// edit (the type: battle/special.hpp). {name, shift, scale, locator, billboard, loop,',
           '// constrain, kind, delay (frames), pair locator, placement, scaled, shot path}.',
           'static const EffectSetting kEffectSettings[%d] = {' % COUNT]
    for k in range(COUNT):
        a = TABLE + k * ENTRY
        name = string(mem.get(a + 4))
        shift = [flt(mem.get(a + 0x10 + 4 * c)) for c in range(3)]
        scale = [flt(mem.get(a + 0x20 + 4 * c, '0x3f800000')) for c in range(3)]
        out.append('    {%s, {%s}, {%s}, %d, %s, %s, %d, %d, %d, %d, %d, %s, %d},' % (
            '"%s"' % name if name is not None else 'nullptr', ', '.join(fl(x) for x in shift), ', '.join(fl(x) for x in scale),
            num(mem.get(a + 0x30)), 'true' if num(mem.get(a + 0x36)) else 'false', 'true' if num(mem.get(a + 0x37)) else 'false',
            num(mem.get(a + 0x39)) & 0xff, num(mem.get(a + 0x3b)) & 0xff, num(mem.get(a + 0x3e)) & 0xffff,
            num(mem.get(a + 0x32)), num(mem.get(a + 0x34)), 'true' if num(mem.get(a + 0x3a)) & 0xff else 'false',
            num(mem.get(a + 0x3c)) & 0xff))
    out.append('};')
    print('\n'.join(out))
    return 0


if __name__ == '__main__':
    sys.exit(main(sys.argv))
