#!/usr/bin/env python3
"""The characters' awakenings (BtlCommand::SetCommandAwakeList / CheckCommandAwake / StepAwakeLoop)
as C++: engine/src/battle/awaketable.inc.

Three tables in the library's data, their addresses read from the decompilation's code: a
character's (from 0, cr3_common_data's) three awakening commands - s16, -1 none - its three story
flags they each need (s32: 9999 none, -1 no awakening), and the charge levels 2 and 3 cost (s32;
level 1 100).

  gen_awake_table.py <decomp.c> <libChaosRings2.so (armv7)> > engine/src/battle/awaketable.inc
"""
import re
import struct
import sys

BASE = 0x10000  # (Ghidra's image base: its DAT_ addresses)


def file_offset(lib, vaddr):
    phoff, = struct.unpack_from('<I', lib, 0x1c)
    phnum, = struct.unpack_from('<H', lib, 0x2c)
    for i in range(phnum):
        p_type, p_offset, p_vaddr, _, p_filesz = struct.unpack_from('<5I', lib, phoff + i * 32)
        if p_type == 1 and p_vaddr <= vaddr < p_vaddr + p_filesz:
            return vaddr - p_vaddr + p_offset
    return None


def body(src, name):
    start = src.index('/* BtlCommand::%s() */' % name)
    return src[start:src.index('\n// ---- ', start)]


def main(argv):
    if len(argv) < 3:
        print(__doc__)
        return 1
    src = open(argv[1], encoding='utf-8', errors='replace').read()
    lib = open(argv[2], 'rb').read()
    s = body(src, 'SetCommandAwakeList')
    commands = int(re.search(r'&DAT_([0-9a-f]+) \+ iVar8 \+ cVar2 \* 6', s).group(1), 16) - BASE
    flags = int(re.search(r'&DAT_([0-9a-f]+) \+ iVar8 \* 2 \+ cVar2 \* 0xc', s).group(1), 16) - BASE
    costs = int(re.search(r'&DAT_([0-9a-f]+) \+ uVar5 \* 4', body(src, 'StepAwakeLoop')).group(1), 16) - BASE
    chars = 8  # (the rows: the flags' table starts 8 rows of 3 s16 on, the commands' table's end)
    cmd = struct.unpack_from('<%dh' % (3 * chars), lib, file_offset(lib, commands))
    flg = struct.unpack_from('<%di' % (3 * chars), lib, file_offset(lib, flags))
    cost = struct.unpack_from('<2i', lib, file_offset(lib, costs))
    assert cmd[:3] == (121, 122, 123), cmd[:3]  # (Darwin's: Executioner, Collbrande, Godslayer)
    out = ['// Generated by tools/gen_awake_table.py from BtlCommand\'s awakening tables - do not edit.',
           '// kAwake[character][level - 1]: the command (-1 none) and the story flag it needs (9999 none).',
           'static const struct { short command; int flag; } kAwake[%d][3] = {' % chars]
    for c in range(chars):
        out.append('    {' + ', '.join('{%d, %d}' % (cmd[3 * c + k], flg[3 * c + k]) for k in range(3)) + '},')
    out.append('};')
    out.append('static const int kAwakeCost[3] = {100, %d, %d}; // (levels 1, 2, 3)' % cost)
    print('\n'.join(out))
    return 0


if __name__ == '__main__':
    sys.exit(main(sys.argv))
