#!/usr/bin/env python3
"""The battle motions' timing table (BtlMotionTable::Initialize) as C++: engine/src/battle/motiontable.inc.

BtlMotionTable is built in code, not read from the data: up to 80 figures (+4: a pointer each to
its name's first four characters, GetMotionIndexFromFileName) x 25 motions (BtlMotionTable's
names: bb01 .. bz03), 0x54 bytes an entry from +0x144:
  +0x00 u32 flags   +0x04 loop start   +0x08 loop end   +0x0c move start   +0x10 move end
  +0x14 move 2 start   +0x18 move 2 end   +0x1c x 10 hit times   +0x44 turn start   +0x48 turn end
  +0x4c effect start   +0x50 s16   +0x52 s16 the effect's location
the times written in frames (defaults -20) and divided by 20 at the end (seconds). This reads the
Initialize function's decompilation (re/android/armv7/decomp.c: tools/re_setup.sh) - its stores
to the table, in order - and the figure names from the library.

  gen_motion_table.py <decomp.c> <libChaosRings2.so (armv7)> > engine/src/battle/motiontable.inc
"""
import re
import struct
import sys


def main(argv):
    if len(argv) < 3:
        print(__doc__)
        return 1
    src = open(argv[1], encoding='utf-8', errors='replace').read()
    lib = open(argv[2], 'rb').read()
    start = src.index('/* BtlMotionTable::Initialize(BtlMain*) */')
    end = src.index('\n// ---- ', start)
    body = src[start:end]
    base = 0x10000  # (Ghidra's image base for the armv7 library)
    names = {}
    entries = {}  # (figure, motion, field) -> value
    store = re.compile(r'\*\((undefined4|undefined2|uint|undefined \*|undefined1) ?\*\)\(param_1 \+ (0x[0-9a-f]+|\d+)\) = (.*);')
    for line in body.splitlines():
        m = store.match(line.strip())
        if not m:
            continue
        kind, off, value = m.group(1), int(m.group(2), 0), m.group(3)
        if off < 0x144:  # a figure's name
            dm = re.match(r'&DAT_([0-9a-f]+)', value)
            if dm and (off - 4) % 4 == 0:
                a = int(dm.group(1), 16) - base
                names[(off - 4) // 4] = lib[a:a + 4].split(b'\0')[0].decode()
            continue
        rel = off - 0x144
        fig, rest = divmod(rel, 0x834)
        if fig >= 80:  # (past the table: the motions' names)
            continue
        mot, field = divmod(rest, 0x54)
        om = re.match(r'\*\(uint \*\)\(param_1 \+ (0x[0-9a-f]+|\d+)\) \| (0x[0-9a-f]+|\d+)', value)
        if om:
            key = (fig, mot, field)
            entries[key] = entries.get(key, 0) | int(om.group(2), 0)
            continue
        if not re.match(r'^(0x[0-9a-f]+|\d+)$', value):
            continue
        v = int(value, 0)
        if kind == 'undefined2':
            v = struct.unpack('<h', struct.pack('<H', v & 0xffff))[0]
        entries[(fig, mot, field)] = v
    out = ['// Generated by tools/gen_motion_table.py from BtlMotionTable::Initialize - do not edit.',
           '// kMotionFigures: the table\'s figures (by their names\' first four characters);',
           '// kMotionStores: {figure, motion, field (the entry\'s byte), value (a float\'s bits, or the',
           '// short / flags)} - the times in frames, the table\'s defaults -20 frames.',
           'static const char* const kMotionFigures[80] = {']
    row = []
    for i in range(80):
        row.append('"%s"' % names[i] if i in names else 'nullptr')
    for i in range(0, 80, 10):
        out.append('    ' + ', '.join(row[i:i + 10]) + ',')
    out.append('};')
    out.append('static const struct { unsigned char figure, motion, field; unsigned value; } kMotionStores[] = {')
    for (fig, mot, field), v in sorted(entries.items()):
        out.append('    {%d, %d, 0x%02x, 0x%08x},' % (fig, mot, field, v & 0xffffffff))
    out.append('};')
    print('\n'.join(out))
    print('// %d figures, %d stores' % (len(names), len(entries)), file=sys.stderr)
    return 0


if __name__ == '__main__':
    sys.exit(main(sys.argv))
