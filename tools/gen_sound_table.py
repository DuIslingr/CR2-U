#!/usr/bin/env python3
"""The sound's tables in the library as C++: engine/src/audio/soundtable.inc.

- kBgmLoop: Cr3UtilSoundPlayBGM's repeat frames (Cr3SoundSetRepeatFrame(table[track - 1]): a
  sample; -1 none), 37 tracks.
- kBgmLoopIpad: the iPad executable's own (its Cr3UtilSoundPlayBGM's table): an AAC packet of its
  bgmNN.caf (1024 samples each, the encoder's priming counted; -1 none).
- kBattleSe: BtlSound::PlaySE(n)'s effects' clips (n 1..0x12b: table[n], -1 none).
- kVoiceFigures / kVoices: Cr3VoiceTable(figure, kind) - 22 figures' first four characters
  ("j001", "m309") and 1000 kinds each, the voice clip (-1 none): kept as {figure, kind, clip}.

Each table's address is read from its function in the decompilation (Ghidra's addresses, base
0x10000), its contents from the library.

  gen_sound_table.py <decomp.c> <libChaosRings2.so (armv7)> <iOS decomp.c> <iOS armv7 Mach-O>
      > engine/src/audio/soundtable.inc
"""
import re
import struct
import sys

BASE = 0x10000


def file_offset(lib, vaddr):
    phoff, = struct.unpack_from('<I', lib, 0x1c)
    phnum, = struct.unpack_from('<H', lib, 0x2c)
    for i in range(phnum):
        p_type, p_offset, p_vaddr, _, p_filesz = struct.unpack_from('<5I', lib, phoff + i * 32)
        if p_type == 1 and p_vaddr <= vaddr < p_vaddr + p_filesz:
            return vaddr - p_vaddr + p_offset
    return None


def macho_offset(macho, vaddr):
    ncmds, = struct.unpack_from('<I', macho, 16)
    p = 28
    for _ in range(ncmds):
        cmd, size = struct.unpack_from('<II', macho, p)
        if cmd == 1:  # LC_SEGMENT
            vm, vs, fo, fs = struct.unpack_from('<4I', macho, p + 24)
            if vm <= vaddr < vm + fs:
                return vaddr - vm + fo
        p += size
    return None


def function(src, signature):
    start = src.index('/* %s */' % signature)
    return src[start:src.index('\n// ---- ', start)]


def main(argv):
    if len(argv) < 5:
        print(__doc__)
        return 1
    src = open(argv[1], encoding='utf-8', errors='replace').read()
    lib = open(argv[2], 'rb').read()
    loops_at = int(re.search(r'&DAT_([0-9a-f]+) \+ \(param_1 \+ -1\) \* 4',
                             function(src, 'Cr3UtilSoundPlayBGM(int, int)')).group(1), 16) - BASE
    se_at = int(re.search(r'&DAT_([0-9a-f]+) \+ param_1 \* 2', function(src, 'BtlSound::PlaySE(int)')).group(1), 16) - BASE
    vt = function(src, "Cr3VoiceTable(char const*, int)")
    names_at = int(re.search(r'\(undefined4 \*\)0x([0-9a-f]+);', vt).group(1), 16) - BASE + 4
    clips_at = int(re.search(r'&DAT_([0-9a-f]+) \+ \(iVar2 \* 1000', vt).group(1), 16) - BASE
    figures = int(re.search(r'while \(iVar2 != (0x[0-9a-f]+|\d+)\)', vt).group(1), 0)

    loops = struct.unpack_from('<37i', lib, file_offset(lib, loops_at))
    ios = open(argv[3], encoding='utf-8', errors='replace').read()
    macho = open(argv[4], 'rb').read()
    i = ios.index('void Cr3UtilSoundPlayBGM(')
    ipad_at = int(re.search(r'&DAT_([0-9a-f]+) \+ \(param_1 - 1U\) \* 4', ios[i:i + 3000]).group(1), 16)
    ipad = struct.unpack_from('<37i', macho, macho_offset(macho, ipad_at))
    se = struct.unpack_from('<300h', lib, file_offset(lib, se_at))
    names = []
    for k in range(figures):
        ptr, = struct.unpack_from('<I', lib, file_offset(lib, names_at) + 4 * k)
        o = file_offset(lib, ptr)
        names.append(lib[o:o + 4].decode('latin-1'))
    clips = struct.unpack_from('<%di' % (figures * 1000), lib, file_offset(lib, clips_at))

    out = ['// Generated by tools/gen_sound_table.py from the library\'s tables - do not edit.',
           '// kBgmLoop[t - 1]: track t\'s repeat frame (-1 none; kBgmLoopIpad: the iPad\'s, in AAC packets);',
           '// kBattleSe[n]: BtlSound::PlaySE(n)\'s',
           '// clip (-1 none); kVoices: Cr3VoiceTable\'s {figure (kVoiceFigures), kind, clip}.',
           'static const int kBgmLoop[37] = {']
    for k in range(0, 37, 8):
        out.append('    ' + ', '.join(str(x) for x in loops[k:k + 8]) + ',')
    out.append('};')
    out.append('static const int kBgmLoopIpad[37] = {')
    for k in range(0, 37, 12):
        out.append('    ' + ', '.join(str(x) for x in ipad[k:k + 12]) + ',')
    out.append('};')
    out.append('static const short kBattleSe[300] = {')
    for k in range(0, 300, 16):
        out.append('    ' + ', '.join(str(x) for x in se[k:k + 16]) + ',')
    out.append('};')
    out.append('static const char* const kVoiceFigures[%d] = {%s};' % (figures, ', '.join('"%s"' % n for n in names)))
    out.append('struct VoiceEntry {')
    out.append('    short figure, kind;')
    out.append('    int clip;')
    out.append('};')
    entries = [(f, k, clips[f * 1000 + k]) for f in range(figures) for k in range(1000) if clips[f * 1000 + k] >= 0]
    out.append('static const VoiceEntry kVoices[%d] = {' % len(entries))
    for k in range(0, len(entries), 6):
        out.append('    ' + ' '.join('{%d, %d, %d},' % e for e in entries[k:k + 6]))
    out.append('};')
    print('\n'.join(out))
    return 0


if __name__ == '__main__':
    sys.exit(main(sys.argv))
