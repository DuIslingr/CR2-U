#!/usr/bin/env python3
"""The EXP tables (BtlData's: lvup_exp - the EXP a character has at each level, 200 -,
chara_sopia_lvup_exp and mons_sopia_lvup_exp - the sopia's, five levels each) as C++:
engine/src/battle/leveltable.inc.

Read from the library's data segment at the symbols' addresses (symbols.txt beside decomp.c).

  gen_level_table.py <decomp.c> <libChaosRings2.so (armv7)> > engine/src/battle/leveltable.inc
"""
import re
import struct
import sys


def file_offset(lib, vaddr):
    phoff, = struct.unpack_from('<I', lib, 0x1c)
    phnum, = struct.unpack_from('<H', lib, 0x2c)
    for i in range(phnum):
        p_type, p_offset, p_vaddr, _, p_filesz = struct.unpack_from('<5I', lib, phoff + i * 32)
        if p_type == 1 and p_vaddr <= vaddr < p_vaddr + p_filesz:
            return vaddr - p_vaddr + p_offset
    return None


def table(lib, symbols, name, count):
    m = re.search(r'([0-9a-f]+) D %s\n' % name, symbols)
    o = file_offset(lib, int(m.group(1), 16))
    return list(struct.unpack_from('<%di' % count, lib, o))


def main(argv):
    if len(argv) < 3:
        print(__doc__)
        return 1
    symbols = open(argv[1].replace('decomp.c', 'symbols.txt')).read()
    lib = open(argv[2], 'rb').read()
    out = ['// Generated by tools/gen_level_table.py from BtlData\'s tables - do not edit.',
           '// kLevelExp[k]: the EXP a character has at level k + 1; the sopia\'s at levels 1..5.']
    for name, var, n in (('lvup_exp', 'kLevelExp', 200), ('chara_sopia_lvup_exp', 'kCharaSopiaExp', 5),
                         ('mons_sopia_lvup_exp', 'kMonsterSopiaExp', 5)):
        v = table(lib, symbols, name, n)
        out.append('static const int %s[%d] = {' % (var, n))
        for k in range(0, n, 10):
            out.append('    ' + ', '.join(str(x) for x in v[k:k + 10]) + ',')
        out.append('};')
    print('\n'.join(out))
    return 0


if __name__ == '__main__':
    sys.exit(main(sys.argv))
